/**
 * Build bundled exercise history seed (load hints + title aliases only — no sessions).
 *
 * Usage:
 *   node scripts/gen-exercise-history-seed.mjs
 *   node scripts/gen-exercise-history-seed.mjs path/to/THE-trainheroic-import.json
 *
 * Output: apps/coach/exercise-history-seed.js
 * The app auto-merges this on boot — no Settings import step.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const defaultImport = join(repoRoot, 'THE-trainheroic-import.json');
const sampleImport = join(repoRoot, 'test/fixtures/trainheroic-import-sample-out.json');
const minImport = join(repoRoot, 'test/fixtures/exercise-history-seed-min.json');
const outPath = join(repoRoot, 'apps/coach/exercise-history-seed.js');

function pickSourcePath(argPath) {
  if (argPath && existsSync(argPath)) return argPath;
  if (existsSync(defaultImport)) return defaultImport;
  if (existsSync(sampleImport)) return sampleImport;
  if (existsSync(minImport)) return minImport;
  throw new Error('No import JSON found. Run import:trainheroic first or pass a path.');
}

function compactSeedFromImport(raw) {
  const loadHints = raw?.state?.strengthState?.loadHints || {};
  const titleAliases =
    raw?.state?.meta?.thTitleAliases || raw?.meta?.titleAliases || raw?.titleAliases || {};

  const cleanedHints = {};
  for (const [exerciseId, hint] of Object.entries(loadHints)) {
    if (!hint || typeof hint !== 'object') continue;
    cleanedHints[exerciseId] = {
      loadKg: Number(hint.loadKg) || 0,
      updatedAt: String(hint.updatedAt || ''),
      source: 'history_seed',
    };
  }

  const payload = {
    loadHints: cleanedHints,
    titleAliases,
  };
  const version = createHash('sha256').update(JSON.stringify(payload)).digest('hex').slice(0, 12);
  return { version, ...payload };
}

function writeSeedModule(seed) {
  const body = `/* Generated by scripts/gen-exercise-history-seed.mjs — do not edit by hand. */
window.EXERCISE_HISTORY_SEED = ${JSON.stringify(seed)};\n`;
  writeFileSync(outPath, body);
}

function main() {
  const sourcePath = pickSourcePath(process.argv[2]);
  const raw = JSON.parse(readFileSync(sourcePath, 'utf8'));
  const seed = compactSeedFromImport(raw);
  writeSeedModule(seed);
  console.log('Wrote', outPath);
  console.log({
    source: sourcePath.split('/').pop(),
    version: seed.version,
    loadHints: Object.keys(seed.loadHints).length,
    titleAliases: Object.keys(seed.titleAliases).length,
    sessions: 0,
  });
}

main();
