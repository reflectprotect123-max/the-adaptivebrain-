/**
 * Generate apps/coach/exercise-search-index.js
 * from hybrid-engine-exercise-library-120.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const libraryPath = join(
  repoRoot,
  'apps/coach/data/exercise-library.json',
);
const outPath = join(repoRoot, 'apps/coach/exercise-search-index.js');

const library = JSON.parse(readFileSync(libraryPath, 'utf8'));

function norm(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

function familyKey(name) {
  const n = norm(name);
  if (/\bdeadlift\b|\brdl\b/.test(n)) return 'deadlift';
  if (/\bsquat\b/.test(n)) return 'squat';
  if (/\bbench\b/.test(n)) return 'bench';
  if (/lateral raise/.test(n)) return 'lateral-raise';
  if (/lat pulldown|\bpulldown\b/.test(n) && !/lateral raise/.test(n)) return 'lat-pulldown';
  if (/\bcurl\b/.test(n) && !/nordic|leg curl|hamstring curl/.test(n)) return 'curl';
  if (/pull up|chin up|pullup|chinup/.test(n)) return 'pull-up';
  if (/\bdip\b/.test(n)) return 'dip';
  if (/push up|pushup/.test(n)) return 'push-up';
  if (/overhead press|shoulder press|military press|ohp/.test(n)) return 'press';
  if (/\brow\b/.test(n)) return 'row';
  if (/\bclean\b|\bsnatch\b|\bjerk\b/.test(n)) return 'olympic';
  if (/farmer|carry|sled|walk/.test(n)) return 'carry';
  if (/plank|dead bug|side plank/.test(n)) return 'isometric';
  if (/bike|row erg|ski erg|run|jump rope|cycling/.test(n)) return 'cardio';
  return '';
}

function extraAliases(name, family) {
  const n = norm(name);
  const out = new Set();
  if (family === 'deadlift') {
    if (n === 'deadlift') {
      out.add('dl');
      out.add('conventional deadlift');
      out.add('barbell deadlift');
    }
    if (n.includes('sumo')) out.add('sumo dl');
    if (n.includes('romanian') || n.includes('rdl')) {
      out.add('rdl');
      out.add('db rdl');
      out.add('dumbbell rdl');
    }
  }
  if (family === 'lateral-raise') {
    out.add('db lateral raise');
    out.add('dumbbell lateral raise');
    out.add('db lat raise');
    out.add('lat raise');
    out.add('side raise');
  }
  if (family === 'lat-pulldown') {
    out.add('lat pull');
    out.add('cable lat pulldown');
    out.add('lat pulldown');
  }
  if (family === 'curl' && n.includes('barbell')) {
    out.add('bb curl');
    out.add('barbell curl');
  }
  if (family === 'curl' && n.includes('dumbbell')) {
    out.add('db curl');
    out.add('dumbbell curl');
  }
  if (family === 'bench') {
    out.add('bp');
    out.add('bench');
  }
  if (family === 'squat' && n.includes('back')) {
    out.add('back squat');
    out.add('squat');
  }
  return [...out];
}

const entries = library.exercises.map((ex) => {
  const family = familyKey(ex.name);
  const aliases = new Set([
    ...(ex.source_aliases || []),
    ...(ex.aliases || []),
    ...extraAliases(ex.name, family),
  ]);
  for (const a of aliases) {
    const na = norm(a);
    if (na) aliases.add(na);
  }
  return {
    id: ex.exercise_id,
    name: ex.name,
    category: ex.category,
    family: family || undefined,
    aliases: [...aliases].filter(Boolean).slice(0, 24),
  };
});

const js =
  '/* GENERATED by scripts/gen-exercise-search-index.mjs — do not hand-edit */\n' +
  '(function (global) {\n' +
  '  global.EXERCISE_SEARCH_INDEX = ' +
  JSON.stringify(entries, null, 2) +
  ';\n' +
  '})(typeof window !== "undefined" ? window : global);\n';

writeFileSync(outPath, js);
console.log('Wrote', outPath, '—', entries.length, 'entries');

const catalogPath = join(repoRoot, 'apps/coach/coach-exercise-catalog.js');
const catalog = entries.map((e) => ({
  id: e.id,
  name: e.name,
  category: e.category,
  builtIn: true,
  source: 'THE-core-120',
}));
const catalogJs =
  '/* GENERATED by scripts/gen-exercise-search-index.mjs — do not hand-edit */\n' +
  '(function (global) {\n' +
  '  global.COACH_EXERCISE_CATALOG = ' +
  JSON.stringify(catalog, null, 2) +
  ';\n' +
  '  global.COACH_EXERCISE_CATALOG_VERSION = ' +
  JSON.stringify('core-120-v1') +
  ';\n' +
  '})(typeof window !== "undefined" ? window : global);\n';
writeFileSync(catalogPath, catalogJs);
console.log('Wrote', catalogPath, '—', catalog.length, 'catalog entries');
